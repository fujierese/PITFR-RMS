        <h3 class="text-lg font-semibold text-slate-900">What is the law?</h3>
        <p class="mt-2">Republic Act No. 10173, known as the Data Privacy Act of 2012, sets rules for handling personal information in the Philippines. In simple terms, organizations should handle personal information fairly, for clear purposes, and with appropriate safeguards.</p>
    </section>
    <section>
        <h3 class="text-lg font-semibold text-slate-900">What does that mean for this system?</h3>
        <p class="mt-2">A reservation may include your name and contact details, organization, event schedule, supporting documents, signature, and the history of decisions. These details are used to process and track the reservation. Access should be limited to people who need the information for their assigned system duties.</p>
    </section>
    <section>
        <h3 class="text-lg font-semibold text-slate-900">What can I do?</h3>
        <p class="mt-2">Depending on the circumstances and legal requirements, you may ask to be informed about processing, request access or correction, object to certain processing, ask about deletion or blocking, or raise a concern through the appropriate channel. Some requests may be limited by legal, records-management, or institutional requirements.</p>
    </section>
